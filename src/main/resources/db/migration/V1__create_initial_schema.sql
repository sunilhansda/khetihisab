
CREATE TABLE customers (
                           customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(100) NOT NULL,
                           phone_number VARCHAR(15),
                           address_code VARCHAR(20),
                           address VARCHAR(500),
                           created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE drivers (
                         driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name VARCHAR(100) NOT NULL,
                         phone_number VARCHAR(15),
                         is_active BOOLEAN NOT NULL DEFAULT TRUE,
                         created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cultivation_jobs (
                                  job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  customer_id BIGINT NOT NULL,
                                  driver_id BIGINT NOT NULL,
                                  job_date DATE NOT NULL,
                                  amount NUMERIC(12, 2) NOT NULL,
                                  status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
                                  notes VARCHAR(500),
                                  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  CONSTRAINT fk_job_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
                                  CONSTRAINT fk_job_driver FOREIGN KEY (driver_id) REFERENCES drivers(driver_id),
                                  CONSTRAINT chk_job_amount CHECK (amount > 0),
                                  CONSTRAINT chk_job_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE payments (
                          payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          customer_id BIGINT NOT NULL,
                          payment_date DATE NOT NULL,
                          amount NUMERIC(12, 2) NOT NULL,
                          payment_method VARCHAR(30) NOT NULL,
                          reference_number VARCHAR(100),
                          notes VARCHAR(500),
                          created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          CONSTRAINT fk_payment_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
                          CONSTRAINT chk_payment_amount CHECK (amount > 0),
                          CONSTRAINT chk_payment_method CHECK (payment_method IN ('CASH', 'UPI', 'BANK_TRANSFER', 'CHEQUE', 'OTHER'))
);

CREATE TABLE payment_allocations (
                                     allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     payment_id BIGINT NOT NULL,
                                     job_id BIGINT NOT NULL,
                                     amount NUMERIC(12, 2) NOT NULL,
                                     created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     CONSTRAINT fk_allocation_payment FOREIGN KEY (payment_id) REFERENCES payments(payment_id),
                                     CONSTRAINT fk_allocation_job FOREIGN KEY (job_id) REFERENCES cultivation_jobs(job_id),
                                     CONSTRAINT chk_allocation_amount CHECK (amount > 0),
                                     CONSTRAINT uk_payment_job UNIQUE (payment_id, job_id)
);

-- Foreign key and search indexes
CREATE INDEX idx_customer_name ON customers(name);
CREATE INDEX idx_customer_address_code ON customers(address_code);
CREATE INDEX idx_customer_phone ON customers(phone_number);
CREATE INDEX idx_job_customer ON cultivation_jobs(customer_id);
CREATE INDEX idx_job_driver ON cultivation_jobs(driver_id);
CREATE INDEX idx_job_date ON cultivation_jobs(job_date);
CREATE INDEX idx_job_status ON cultivation_jobs(status);
CREATE INDEX idx_job_customer_date ON cultivation_jobs(customer_id, job_date);
CREATE INDEX idx_payment_customer ON payments(customer_id);
CREATE INDEX idx_payment_date ON payments(payment_date);
CREATE INDEX idx_payment_customer_date ON payments(customer_id, payment_date);
CREATE INDEX idx_allocation_job ON payment_allocations(job_id);
CREATE INDEX idx_allocation_payment ON payment_allocations(payment_id);
